"""F-12·N-4 고정 측정 표본(장면 목록 파일)을 만든다.

규칙 (spec "확정한 값" F-12): 학습 장면 frame_id 전체를 오름차순 정렬한 뒤
numpy.random.default_rng(42).permutation 순서로 섞고, 앞 100개·1,000개를 고른다.
각 파일 안의 id는 오름차순으로 적는다(처리 순서는 프로그램이 다시 정렬). 7,481은 전체.
frame_id는 label_2 파일명에서 얻는다(학습 세트의 기준 목록).

사용:
    .venv/bin/python scripts/make_samples.py [--root ~/data/kitti] [--out samples]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402

from kitti import config  # noqa: E402
from kitti import io as kio  # noqa: E402

SEED: int = 42
SIZES: tuple[int, ...] = (100, 1000)
DEFAULT_OUT: Path = Path(__file__).resolve().parents[1] / "samples"


def make_samples(all_ids: list[int], sizes: tuple[int, ...] = SIZES, seed: int = SEED) -> dict[int, list[int]]:
    """{규모: 오름차순 frame_id 목록}. 전체 규모(len(all_ids))도 포함한다."""
    ordered = np.array(sorted(all_ids), dtype=np.int64)
    shuffled = ordered[np.random.default_rng(seed).permutation(ordered.size)]
    out = {n: sorted(int(f) for f in shuffled[:n]) for n in sizes}
    out[int(ordered.size)] = [int(f) for f in ordered]
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="고정 측정 표본 목록 생성")
    parser.add_argument("--root", default=str(config.KITTI_ROOT))
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args(argv)
    ids = kio.list_frame_ids(args.root)["label_2"]
    if len(ids) != config.EXPECTED_TRAINING_FRAMES:
        print(f"warning: label_2 has {len(ids)} frames (expected {config.EXPECTED_TRAINING_FRAMES})")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for n, sample in sorted(make_samples(ids).items()):
        header = [
            f"# KITTI 3D object training sample: {n} frames",
            f"# rule: sort all {len(ids)} training frame_ids (from label_2) ascending,",
            f"#       shuffle with numpy.random.default_rng({SEED}).permutation, take the first {n};",
            "#       ids below are listed ascending. Full set = all ids.",
            "# generated by scripts/make_samples.py",
        ]
        path = out / f"sample_{n}.txt"
        path.write_text("\n".join(header + [str(f) for f in sample]) + "\n", encoding="utf-8")
        print(f"{path}: {len(sample)} ids, first={sample[:5]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
